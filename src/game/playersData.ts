export function getEffectiveCard(card: PlayerCard, level: number): PlayerCard {
  const bonus = Math.max(0, level - 1);
  if (bonus === 0) return card;
  const boost = (val: number) => Math.min(99, val + bonus);
  return {
    ...card,
    level,
    ovr: Math.min(99, card.ovr + Math.floor(bonus * 0.7)),
    stats: {
      threePoint: boost(card.stats.threePoint),
      midRange: boost(card.stats.midRange),
      dunk: boost(card.stats.dunk),
      handle: boost(card.stats.handle),
      defense: boost(card.stats.defense),
      speed: boost(card.stats.speed),
      rebound: boost(card.stats.rebound),
      pass: boost(card.stats.pass),
    },
  };
}
